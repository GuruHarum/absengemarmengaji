"use strict";
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('../../.test-tools/node_modules/@electric-sql/pglite');
test('student import preserves existing data, isolates identifiers and enforces teacher scope', async () => {
    const db = new PGlite();
    const manager = '00000000-0000-0000-0000-000000000001', teacher = '00000000-0000-0000-0000-000000000002';
    const login = async (id) => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id || '']); await db.exec(id ? 'set role authenticated' : 'set role anon'); };
    const row = (extra = {}) => ({ nama: 'Ahmad', nis: '0001', nisn: '0012345678', kelas: 'IV A', guru: 'guru a', row: 2, ...extra });
    const run = async (rows) => (await db.query('select public.import_students($1::jsonb) as result', [JSON.stringify(rows)])).rows[0].result;
    try {
        await db.exec(`create role anon;create role authenticated;create schema auth;create schema app_private;
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create function app_private.is_manager() returns boolean language sql stable as $$select auth.uid()='${manager}'::uuid$$;
   create function app_private.teacher_name() returns text language sql stable as $$select case when auth.uid()='${teacher}'::uuid then 'Guru A' else null end$$;
   create table public.teacher_class_access(user_id uuid,class_name text,primary key(user_id,class_name));
   create table public.user_roles(user_id uuid,role text,teacher_id text);
   insert into user_roles values('${teacher}','guru','1');
   insert into teacher_class_access values('${teacher}','4A');
   create function app_private.owns_class(value text) returns boolean language sql stable security definer as $$select exists(select 1 from public.teacher_class_access where user_id=auth.uid() and class_name=value)$$;
   grant usage on schema auth,app_private to authenticated,anon;
   create table public.teachers(id bigint generated by default as identity primary key,nama text,nama_lengkap text,attendance_enabled boolean default true);
   insert into teachers(nama) values('Guru A'),('Guru B');
   create table public.students(id bigint generated by default as identity primary key,"nama siswa" text not null,"nama guru" text not null,kelas text not null);
   create table public.teaching_assignments(id uuid primary key default gen_random_uuid(),teacher_id text,subject text,class_name text,academic_year_start integer,active boolean default true,created_by uuid,roster_mode text);
   create unique index teaching_assignment_active on teaching_assignments(academic_year_start,subject,class_name) where active;
   create table public.assessment_group_members(assignment_id uuid references teaching_assignments(id),student_id text,academic_year_start integer,active boolean default true,primary key(assignment_id,student_id));
   create unique index one_tahfidz_group_per_year on assessment_group_members(student_id,academic_year_start) where active;
   alter table public.students enable row level security;
   grant select on public.students to authenticated,anon;
   create policy visible on public.students for select to authenticated using(app_private.is_manager() or ("nama guru"=app_private.teacher_name() and app_private.owns_class(kelas)));
   create policy public_visible on public.students for select to anon using(true);
   insert into public.students("nama siswa","nama guru",kelas) values('Ahmad','Guru A','4A'),('Kosong','',''),('Kembar','Guru A','4A'),('Kembar','Guru B','4A');`);
        const migration = fs.readFileSync('supabase/student-import.sql', 'utf8');
        await db.exec(migration);
        await db.exec(migration);
        await login(manager);
        await db.exec('begin');
        const linked = await run([row({ guru: 'Guru B' })]);
        await run([row({ kelas: 'kelas I UMAR BIN KHATTAB', guru: 'Guru B' })]);
        assert.equal(linked.updated, 1);
        assert.equal(linked.created, 0);
        assert.equal(linked.skipped, 0);
        assert.deepEqual((await db.query('select kelas,"nama guru" as guru from students where id=1')).rows[0], { kelas: '1 Umar Bin Khattab', guru: 'Guru B' });
        assert.equal((await db.query('select student_id from student_identifiers where nis=$1', ['0001'])).rows[0].student_id, 1);
        const ambiguous = await run([row({ nama: 'Kembar', nis: '0088' })]);
        assert.equal(ambiguous.updated, 1);
        assert.equal(ambiguous.skipped, 0);
        assert.equal((await db.query("select count(*) as n from students where \"nama siswa\"='Kembar'")).rows[0].n, 1);
        assert.equal((await db.query('select count(*) as n from student_identifiers where nis=$1', ['0088'])).rows[0].n, 1);
        const distinct = await run([row({ nama: 'Kembar', nis: '0089' })]);
        assert.equal(distinct.created, 1, 'different NIS must retain a separate student');
        await db.exec('rollback');
        await db.exec('begin');
        const sharedTeacher = await run([
            row({ nama: 'Siswa Uji A', nis: '00901', nisn: '', guru: 'Siti Aminah, S.Pd.', guru_tahfidz: 'SITI\u00a0AMINAH S Pd' }),
            row({ nama: 'Siswa Uji B', nis: '00902', nisn: '', guru: 'Siti\u200b Aminah, S.Pd.', guru_tahfidz: 'Siti Aminah, S.Pd.' })
        ]);
        assert.equal(sharedTeacher.teachers_created, 1, 'one new teacher must be reused across both subjects and every row of the same upload');
        await db.exec('rollback');
        await db.exec('reset role');
        await db.exec("update teachers set nama_lengkap='Ahmad Abdullah' where id=1; update teachers set nama_lengkap='Bilal Badr' where id=2");
        await login(manager);
        const fullNames = await run([row({ guru: '  AHMAD   ABDULLAH ', guru_tahfidz: 'bilal badr' })]);
        assert.equal(fullNames.teachers_created, 0);
        assert.equal(fullNames.tahfidz_added, 1);
        assert.equal((await db.query('select "nama guru" as guru from students where id=1')).rows[0].guru, 'Guru A');
        const bothSubjects = await run([row({ guru: 'Ahmad Abdullah', guru_tahfidz: 'AHMAD\u00a0ABDULLAH' })]);
        assert.equal(bothSubjects.teachers_created, 0);
        await db.exec('reset role');
        assert.equal((await db.query("select a.teacher_id from assessment_group_members m join teaching_assignments a on a.id=m.assignment_id where m.student_id='1' and m.active")).rows[0].teacher_id, '1');
        await db.exec("insert into teachers(nama,nama_lengkap,attendance_enabled) values('Duplikat Tahfidz','Ahmad Abdullah',false)");
        await login(manager);
        assert.equal((await run([row({ guru: 'Ahmad Abdullah', guru_tahfidz: 'Ahmad Abdullah' })])).teachers_created, 0);
        await db.exec('reset role');
        assert.equal((await db.query("select a.teacher_id from assessment_group_members m join teaching_assignments a on a.id=m.assignment_id where m.student_id='1' and m.active")).rows[0].teacher_id, '1');
        await db.exec("delete from teachers where nama='Duplikat Tahfidz'");
        await login(manager);
        await db.exec('reset role');
        await db.exec("insert into teachers(nama,nama_lengkap) values('Ahmad Abdullah','Orang Berbeda')");
        await login(manager);
        assert.equal((await run([row({ guru: 'Ahmad Abdullah' })])).teachers_created, 0);
        assert.equal((await db.query('select "nama guru" as guru from students where id=1')).rows[0].guru, 'Guru A');
        await db.exec('reset role');
        await db.exec("update teachers set nama_lengkap='Ahmad Abdullah' where nama='Ahmad Abdullah'");
        await login(manager);
        await assert.rejects(run([row({ guru: 'Ahmad Abdullah' })]), /ambigu/);
        await db.exec('reset role');
        await db.exec("delete from teachers where nama='Ahmad Abdullah'");
        await db.exec("update teachers set nama_lengkap=null; delete from assessment_group_members; delete from teaching_assignments; delete from student_identifiers");
        await login(manager);
        let result = await run([row({ guru_tahfidz: 'Guru B' })]);
        assert.equal(result.updated, 1);
        assert.equal(result.created, 0);
        assert.equal(result.tahfidz_added, 1);
        result = await run([row({ guru_tahfidz: 'Guru B' })]);
        assert.equal(result.unchanged, 1);
        assert.equal(result.tahfidz_added, 0);
        result = await run([row({ kelas: 'V B', guru: 'Guru C Baru', guru_tahfidz: 'Guru D Baru', nisn: '' })]);
        assert.equal(result.updated, 1);
        assert.equal(result.teachers_created, 2);
        assert.equal(result.tahfidz_added, 1);
        await db.exec('reset role');
        assert.equal((await db.query("select nama_lengkap from teachers where nama='Guru C Baru'")).rows[0].nama_lengkap, 'Guru C Baru');
        await login(manager);
        assert.equal((await db.query('select kelas from students where id=1')).rows[0].kelas, '5B');
        assert.equal((await db.query('select nisn from student_identifiers where student_id=1')).rows[0].nisn, '0012345678');
        assert.equal((await db.query('select count(*) as n from students')).rows[0].n, 4);
        result = await run([row({ nama: '', kelas: '', guru: '', nisn: '', guru_tahfidz: '' })]);
        assert.equal(result.unchanged, 1);
        result = await run([row({ nama: 'Baru', nis: '0002', nisn: '', kelas: 'VI B', guru: 'GURU D BARU', guru_tahfidz: 'guru c baru' })]);
        assert.equal(result.created, 1);
        assert.equal(result.teachers_created, 0);
        result = await run([row({ nama: '', nis: '0003', nisn: '', kelas: '', guru: '' })]);
        assert.equal(result.created, 1);
        await assert.rejects(run([row({ nis: '' })]), /NIS wajib/);
        await assert.rejects(run([row(), row()]), /NIS berulang/);
        await db.exec('reset role');
        const assignments = (await db.query("select * from assessment_group_members where student_id='1'")).rows;
        assert.equal(assignments.filter(row => row.active).length, 1);
        assert.equal(assignments.filter(row => !row.active).length, 1);
        const oldCount = assignments.length;
        await login(manager);
        const future = (await db.query('select import_students($1::jsonb,2030) as result', [JSON.stringify([row({ guru: 'Guru A', kelas: 'VII A', guru_tahfidz: 'Guru B' })])])).rows[0].result;
        assert.equal(future.tahfidz_added, 1);
        await login(teacher);
        assert.equal((await db.query('select id from students where id=1')).rows.length, 1);
        await assert.rejects(run([row({ guru_tahfidz: 'Guru A' })]), /admin\/koordinator/);
        await assert.rejects(run([row({ nama: 'Tidak boleh', kelas: 'VIII A' })]), /hak akses/);
        await assert.rejects(run([row({ nis: '0002', guru: 'Guru A' })]), /hak akses/);
        await assert.rejects(run([row({ nama: 'Rollback', nis: '0099', nisn: '' }), row({ nis: '' })]), /NIS wajib/);
        assert.equal((await db.query("select id from students where \"nama siswa\"='Rollback'")).rows.length, 0);
        await login(null);
        assert.ok((await db.query('select * from students')).rows.length > 0);
        assert.equal(Object.keys((await db.query('select * from students limit 1')).rows[0]).includes('nis'), false);
        await assert.rejects(db.query('select * from student_identifiers'), /permission denied/);
        await assert.rejects(run([row()]), /permission denied/);
    }
    finally {
        await db.close();
    }
});
